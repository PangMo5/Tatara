func signing(_ command: String) throws {
  let temp = try URL(fileURLWithPath: required("RUNNER_TEMP"))
  let keychain = temp.appendingPathComponent("tatara.keychain-db")
  switch command {
  case "import-certificate":
    guard let certificate = try Data(base64Encoded: required("CERT_P12_BASE64"), options: .ignoreUnknownCharacters)
    else { throw ToolError("Invalid certificate encoding.") }
    let cert = temp.appendingPathComponent("cert.p12")
    try certificate.write(to: cert)
    let password = try required("KEYCHAIN_PASSWORD")
    try run("security", ["create-keychain", "-p", password, keychain.path], secret: true)
    try run("security", ["set-keychain-settings", "-lut", "21600", keychain.path])
    try run("security", ["unlock-keychain", "-p", password, keychain.path], secret: true)
    try run(
      "security",
      ["import", cert.path, "-k", keychain.path, "-P", required("CERT_PASSWORD"), "-T", "/usr/bin/codesign"],
      secret: true,
    )
    try run("security", ["set-key-partition-list", "-S", "apple-tool:,apple:", "-s", "-k", password, keychain.path], secret: true)
    try run("security", ["list-keychains", "-d", "user", "-s", keychain.path])
  case "sign":
    let binary = path("DerivedData/Build/Products/Release/tatara").path
    try run("codesign", ["--force", "--sign", "Developer ID Application", "--options", "runtime", "--timestamp", binary])
    try run("codesign", ["--verify", "--strict", binary])
  case "notarize":
    let key = temp.appendingPathComponent("notary.p8")
    try write(required("AC_API_KEY_P8"), key)
    let archive = temp.appendingPathComponent("tatara.zip")
    try run("ditto", ["-c", "-k", path("DerivedData/Build/Products/Release/tatara").path, archive.path])
    let result = path(".artifacts/notarization.json")
    try run(
      "xcrun",
      [
        "notarytool",
        "submit",
        archive.path,
        "--key",
        key.path,
        "--key-id",
        required("AC_API_KEY_ID"),
        "--issuer",
        required("AC_API_ISSUER_ID"),
        "--wait",
        "--output-format",
        "json",
      ],
      output: result,
    )
    try require(json(result)["status"] as? String == "Accepted", "Notarization was not accepted.")
  case "clean-signing":
    for name in ["cert.p12", "notary.p8"] {
      let file = temp.appendingPathComponent(name)
      if fm.fileExists(atPath: file.path) {
        try fm.removeItem(at: file)
      }
    }
    if fm.fileExists(atPath: keychain.path) {
      try run("security", ["delete-keychain", keychain.path])
    }
  default: throw ToolError("Unknown signing operation.")
  }
}

func release(_ command: String) throws {
  let tag = try environment["RELEASE_TAG"] ?? "v\(version())"
  let dist = path("dist")
  switch command {
  case "validate-release":
    try require(tag == "v\(version())", "Tag does not match appVersion.")
    try run("git", ["merge-base", "--is-ancestor", "HEAD", "origin/main"])
    _ = try releaseNotes()
  case "assemble-release":
    try fm.createDirectory(at: dist, withIntermediateDirectories: true)
    try run(
      "git",
      [
        "archive",
        "--format=tar.gz",
        "--prefix=Tatara-\(version())/",
        "--output=\(dist.appendingPathComponent("Tatara-\(version())-source.tar.gz").path)",
        "HEAD",
      ],
    )
    try formula(artifacts: dist, output: dist.appendingPathComponent("tatara.rb"))
    try write(releaseNotes(), dist.appendingPathComponent("release-notes.md"))
    let files = try fm.contentsOfDirectory(at: dist, includingPropertiesForKeys: nil)
      .filter { $0.lastPathComponent.hasSuffix(".tar.gz") }.sorted { $0.path < $1.path }
    try write(
      files.map { try "\(digest($0))  \($0.lastPathComponent)" }.joined(separator: "\n") + "\n",
      dist.appendingPathComponent("SHA256SUMS"),
    )
  case "publish":
    let assets = try fm.contentsOfDirectory(at: dist, includingPropertiesForKeys: nil)
      .filter { $0.lastPathComponent.hasSuffix(".tar.gz") }.map(\.path)
    try run(
      "gh",
      ["release", "create", tag] + assets + [
        dist.appendingPathComponent("SHA256SUMS").path,
        dist.appendingPathComponent("tatara.rb").path,
        "--verify-tag",
        "--title",
        tag,
        "--notes-file",
        dist.appendingPathComponent("release-notes.md").path,
      ],
    )
  case "verify-release":
    let download = try temporary("download")
    defer { try? fm.removeItem(at: download) }
    try run("gh", ["release", "download", tag, "--pattern", "*.tar.gz", "--pattern", "SHA256SUMS", "--dir", download.path])
    for line in try read(download.appendingPathComponent("SHA256SUMS")).split(separator: "\n") {
      let fields = line.split(whereSeparator: \.isWhitespace)
      try require(fields.count == 2 && !fields[1].contains("/"), "Invalid checksum manifest entry.")
      try require(digest(download.appendingPathComponent(String(fields[1]))) == fields[0], "Published checksum mismatch.")
    }
  case "update-tap":
    _ = try required("GH_TOKEN")
    let checkout = try temporary("tap")
    defer { try? fm.removeItem(at: checkout) }
    try run("gh", ["auth", "setup-git"])
    try run("git", ["clone", "https://github.com/PangMo5/homebrew-tap.git", checkout.path])
    try write(read(dist.appendingPathComponent("tatara.rb")), checkout.appendingPathComponent("Formula/tatara.rb"))
    try run("git", ["config", "user.name", "github-actions[bot]"], cwd: checkout)
    try run("git", ["config", "user.email", "41898282+github-actions[bot]@users.noreply.github.com"], cwd: checkout)
    try run("git", ["add", "Formula/tatara.rb"], cwd: checkout)
    try run("git", ["commit", "-m", "Update Tatara formula"], cwd: checkout)
    try run("git", ["push"], cwd: checkout)
  default: throw ToolError("Unknown release operation.")
  }
}

do {
  guard let command = arguments.first else { throw ToolError("Usage: swift Scripts/Tatara.swift COMMAND [ARGUMENTS]") }
  let args = Array(arguments.dropFirst())
  switch command {
  case "version": try print(version())
  case "localizations": try localizations(check: args.contains("--check"))
  case "notices": try notices(check: args.contains("--check"))
  case "release-notes":
    if let file = args.first {
      try write(releaseNotes(), URL(fileURLWithPath: file))
    } else {
      try print(
        releaseNotes(),
        terminator: "",
      )
    }
  case "check-tests": try require(args.count == 1, "Expected a test log.")
    try checkTests(URL(fileURLWithPath: args[0]))
  case "package":
    let arch = args.count > 1 ? args[1] : try required("ARCH")
    try package(
      products: URL(fileURLWithPath: args.first ?? path("DerivedData/Build/Products/Release").path),
      architecture: arch,
      output: URL(fileURLWithPath: args.count > 2 ? args[2] : path("dist").path),
    )
  case "formula": try require(args.count == 2, "Expected artifacts and output paths.")
    try formula(artifacts: URL(fileURLWithPath: args[0]), output: URL(fileURLWithPath: args[1]))
  case "install-local":
    try installLocal(
      products: URL(fileURLWithPath: args.first ?? path("DerivedData/Build/Products/Release").path),
      prefix: URL(fileURLWithPath: args.count > 1 ? args[1] : fm.homeDirectoryForCurrentUser
        .appendingPathComponent(".local/share/tatara/local").path),
    )
  case "generate": try generate(locked: args.contains("--locked"))
  case "build": try build(args.first ?? "Debug")
  case "release-build": try generate()
    try build("Release", extra: ["ARCHS=\(required("ARCH"))", "ONLY_ACTIVE_ARCH=NO", "CODE_SIGNING_ALLOWED=NO"])
    try signing("sign")
  case "test": try tests()
  case "lint": try lint()
  case "format": try run(
      "swiftformat",
      [
        "TataraCore",
        "TataraKit",
        "TataraSystem",
        "TataraGitHub",
        "TataraPersistence",
        "TataraTUI",
        "TataraTests",
        "Scripts",
        "Project.swift",
        "Tuist/Package.swift",
      ],
    )
  case "smoke": try smoke(args)
  case "import-certificate", "sign", "notarize", "clean-signing": try signing(command)
  case "validate-release", "assemble-release", "publish", "verify-release", "update-tap": try release(command)
  default: throw ToolError("Unknown command: \(command)")
  }
} catch {
  FileHandle.standardError.write(Data("\(error)\n".utf8))
  exit(1)
}
