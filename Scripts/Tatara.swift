func signing(_ command: String) throws {
  let temp = try URL(fileURLWithPath: required("RUNNER_TEMP"))
  let keychain = temp.appendingPathComponent("tatara.keychain-db")
  switch command {
  case "import-certificate":
    guard let certificate = try Data(base64Encoded: required("CERT_P12_BASE64"), options: .ignoreUnknownCharacters)
    else { throw ToolError("Invalid certificate encoding.") }
    let cert = temp.appendingPathComponent("cert.p12")
    try certificate.write(to: cert)
    let password = try required("KEYCHAIN_PASSWORD")
    try run("security", ["create-keychain", "-p", password, keychain.path], secret: true)
    try run("security", ["set-keychain-settings", "-lut", "21600", keychain.path])
    try run("security", ["unlock-keychain", "-p", password, keychain.path], secret: true)
    try run(
      "security",
      ["import", cert.path, "-k", keychain.path, "-P", required("CERT_PASSWORD"), "-T", "/usr/bin/codesign"],
      secret: true,
    )
    try run("security", ["set-key-partition-list", "-S", "apple-tool:,apple:", "-s", "-k", password, keychain.path], secret: true)
    try run("security", ["list-keychains", "-d", "user", "-s", keychain.path])

  case "sign":
    let directory = try products(architecture: environment["ARCH"])
    let flags = [
      "--force",
      "--sign",
      "Developer ID Application",
      "--options",
      "runtime",
      "--timestamp",
    ]
    for file in try runtimeFiles(in: directory).reversed() {
      let identity = file.lastPathComponent == "tatara" ? ["--identifier", "dev.PangMo5.tatara"] : []
      try run("codesign", flags + identity + [file.path])
      try run("codesign", ["--verify", "--strict", file.path])
    }

  case "notarize":
    let key = temp.appendingPathComponent("notary.p8")
    try write(required("AC_API_KEY_P8"), key)
    let archive = temp.appendingPathComponent("tatara.zip")
    let directory = try temporary("notarization")
    defer { try? fm.removeItem(at: directory) }
    let bin = directory.appendingPathComponent("bin")
    try fm.createDirectory(at: bin, withIntermediateDirectories: true)
    for file in try runtimeFiles(in: products(architecture: environment["ARCH"])) {
      try fm.copyItem(at: file, to: bin.appendingPathComponent(file.lastPathComponent))
    }
    try run("ditto", ["-c", "-k", "--keepParent", bin.path, archive.path])
    let result = path(".artifacts/notarization.json")
    try run(
      "xcrun",
      [
        "notarytool",
        "submit",
        archive.path,
        "--key",
        key.path,
        "--key-id",
        required("AC_API_KEY_ID"),
        "--issuer",
        required("AC_API_ISSUER_ID"),
        "--wait",
        "--output-format",
        "json",
      ],
      output: result,
    )
    try require(json(result)["status"] as? String == "Accepted", "Notarization was not accepted.")

  case "clean-signing":
    for name in ["cert.p12", "notary.p8"] {
      let file = temp.appendingPathComponent(name)
      if fm.fileExists(atPath: file.path) {
        try fm.removeItem(at: file)
      }
    }
    if fm.fileExists(atPath: keychain.path) {
      try run("security", ["delete-keychain", keychain.path])
    }

  default: throw ToolError("Unknown signing operation.")
  }
}

func release(_ command: String) throws {
  let tag = try environment["RELEASE_TAG"] ?? "v\(version())"
  let dist = path("dist")
  switch command {
  case "validate-release":
    try toolchain(requiresReleaseBuild: true)
    try require(tag == "v\(version())", "Tag does not match TataraVersion.current.")
    try run("git", ["merge-base", "--is-ancestor", "HEAD", "origin/main"])
    _ = try releaseNotes()

  case "assemble-release":
    try fm.createDirectory(at: dist, withIntermediateDirectories: true)
    try run(
      "git",
      [
        "archive",
        "--format=tar.gz",
        "--prefix=Tatara-\(version())/",
        "--output=\(dist.appendingPathComponent("Tatara-\(version())-source.tar.gz").path)",
        "HEAD",
      ],
    )
    try write(releaseNotes(), dist.appendingPathComponent("release-notes.md"))
    let files = try fm.contentsOfDirectory(at: dist, includingPropertiesForKeys: nil)
      .filter { $0.lastPathComponent.hasSuffix(".tar.gz") }.sorted { $0.path < $1.path }
    try write(
      files.lazy.map { try "\(digest($0))  \($0.lastPathComponent)" }.joined(separator: "\n") + "\n",
      dist.appendingPathComponent("SHA256SUMS"),
    )

  case "publish":
    let assets = try fm.contentsOfDirectory(at: dist, includingPropertiesForKeys: nil)
      .filter { $0.lastPathComponent.hasSuffix(".tar.gz") }.map(\.path)
    try run(
      "gh",
      ["release", "create", tag] + assets + [
        dist.appendingPathComponent("SHA256SUMS").path,
        "--verify-tag",
        "--title",
        tag,
        "--notes-file",
        dist.appendingPathComponent("release-notes.md").path,
      ],
    )

  case "verify-release":
    let download = try temporary("download")
    defer { try? fm.removeItem(at: download) }
    try run("gh", ["release", "download", tag, "--pattern", "*.tar.gz", "--pattern", "SHA256SUMS", "--dir", download.path])
    for line in try read(download.appendingPathComponent("SHA256SUMS")).split(separator: "\n") {
      let fields = line.split(whereSeparator: \.isWhitespace)
      try require(fields.count == 2 && !fields[1].contains("/"), "Invalid checksum manifest entry.")
      try require(digest(download.appendingPathComponent(String(fields[1]))) == fields[0], "Published checksum mismatch.")
    }

  default: throw ToolError("Unknown release operation.")
  }
}

