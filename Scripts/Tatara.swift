struct ToolError: Error, CustomStringConvertible {
  var description: String
  init(_ message: String) {
    description = message
  }
}

let fm = FileManager.default
let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let environment = ProcessInfo.processInfo.environment
let arguments = Array(CommandLine.arguments.dropFirst())

func require(_ condition: Bool, _ message: String) throws {
  if !condition {
    throw ToolError(message)
  }
}

func path(_ name: String) -> URL {
  root.appendingPathComponent(name)
}

func read(_ url: URL) throws -> String {
  try String(contentsOf: url, encoding: .utf8)
}

func write(_ text: String, _ url: URL) throws {
  try fm.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
  try text.write(to: url, atomically: true, encoding: .utf8)
}

func json(_ url: URL) throws -> [String: Any] {
  guard let value = try JSONSerialization.jsonObject(with: Data(contentsOf: url)) as? [String: Any]
  else { throw ToolError("Invalid JSON: \(url.path)") }
  return value
}

func required(_ key: String) throws -> String {
  guard let value = environment[key], !value.isEmpty else { throw ToolError("Missing environment variable: \(key)") }
  return value
}

func temporary(_ name: String) throws -> URL {
  let value = fm.temporaryDirectory.appendingPathComponent("tatara-\(name)-\(UUID().uuidString)")
  try fm.createDirectory(at: value, withIntermediateDirectories: false, attributes: [.posixPermissions: 0o700])
  return value
}

@discardableResult
func run(
  _ command: String,
  _ args: [String] = [],
  cwd: URL = root,
  capture: Bool = false,
  output: URL? = nil,
  secret: Bool = false,
) throws -> String {
  let process = Process()
  process.executableURL = URL(fileURLWithPath: "/usr/bin/env")
  process.arguments = [command] + args
  process.currentDirectoryURL = cwd
  // A temporary file avoids pipe-capacity deadlocks for large command output.
  let directory = try temporary("command")
  defer { try? fm.removeItem(at: directory) }
  let destination = output ?? directory.appendingPathComponent("stdout")
  var handle: FileHandle?
  if capture || output != nil {
    try fm.createDirectory(at: destination.deletingLastPathComponent(), withIntermediateDirectories: true)
    fm.createFile(atPath: destination.path, contents: nil)
    handle = try FileHandle(forWritingTo: destination)
    process.standardOutput = handle
  }
  defer { try? handle?.close() }
  try process.run()
  process.waitUntilExit()
  try require(
    process.terminationStatus == 0,
    "\(command) failed with status \(process.terminationStatus)\(secret ? "" : ": " + args.joined(separator: " "))",
  )
  return capture ? try read(destination) : ""
}

func version() throws -> String {
  let source = try read(path("Project.swift"))
  let regex = try NSRegularExpression(pattern: #"(?m)^let appVersion = "(\d+\.\d+\.\d+)"$"#)
  guard let match = regex.firstMatch(in: source, range: NSRange(source.startIndex..., in: source)), let range = Range(
    match.range(at: 1),
    in: source,
  ) else { throw ToolError("Project.swift must declare appVersion.") }
  return String(source[range])
}

func digest(_ url: URL) throws -> String {
  let handle = try FileHandle(forReadingFrom: url)
  defer { try? handle.close() }
  var hasher = SHA256()
  while let data = try handle.read(upToCount: 1_048_576), !data.isEmpty {
    hasher.update(data: data)
  }
  return hasher.finalize().map { String(format: "%02x", $0) }.joined()
}

func swiftLiteral(_ text: String) throws -> String {
  let encoded = try String(decoding: JSONEncoder().encode(text), as: UTF8.self)
  return encoded.replacingOccurrences(of: "\\/", with: "/")
}

func generated(_ text: String, at url: URL, check: Bool) throws {
  if check {
    try require(read(url) == text, "Generated file is stale: \(url.lastPathComponent)")
  } else if (try? read(url)) != text {
    try write(text, url)
  }
}

func localizations(check: Bool) throws {
  let catalog = try json(path("SharedResources/Localizable.xcstrings"))
  guard let strings = catalog["strings"] as? [String: [String: Any]] else { throw ToolError("Missing catalog strings.") }
  let locales = ["en", "ko", "ja", "zh-Hans", "zh-Hant"]
  var lines = ["// Generated by Scripts/Tatara.swift localizations. Do not edit.",
               "// SPDX-FileCopyrightText: 2026 PangMo5 and contributors",
               "// SPDX-" + "License-Identifier: AGPL-3.0-only", "", "enum LocalizedStrings {",
               "  static let values: [String: [String: String]] = ["]
  for locale in locales {
    try lines.append("    \(swiftLiteral(locale)): [")
    for key in strings.keys.sorted() {
      guard let translations = strings[key]?["localizations"] as? [String: [String: Any]],
            let unit = translations[locale]?["stringUnit"] as? [String: String], unit["state"] == "translated",
            let value = unit["value"],
            !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
      else { throw ToolError("Missing translation: \(locale)/\(key)") }
      try lines.append("      \(swiftLiteral(key)): \(swiftLiteral(value)),")
    }
    lines.append("    ],")
  }
  lines += ["  ]", "}", ""]
  try generated(lines.joined(separator: "\n"), at: path("TataraTUI/Sources/Generated/LocalizedStrings.swift"), check: check)
  print("Validated \(strings.count) strings across \(locales.count) locales.")
}

func notices(check: Bool) throws {
  guard let pins = try json(path("Tuist/Package.resolved"))["pins"] as? [[String: Any]]
  else { throw ToolError("Missing package pins.") }
  if fm.fileExists(atPath: path("Scripts/Smoke/Package.resolved").path),
     let toolPins = try json(path("Scripts/Smoke/Package.resolved"))["pins"] as? [[String: Any]]
  {
    for pin in toolPins {
      let revision = (pin["state"] as? [String: String])?["revision"]
      try require(
        pins
          .contains {
            $0["identity"] as? String == pin["identity"] as? String && ($0["state"] as? [String: String])?["revision"] == revision
          },
        "Smoke dependency is not covered by the resolved notices. Align its pin with Tuist/Package.resolved.",
      )
    }
  }
  var parts = ["# Third-Party Notices", "", "Tatara is licensed under AGPL-3.0-only. Dependencies retain their own licenses.",
               "Versions below come from Tuist/Package.resolved. Notices include build dependencies and vendored components.", "",
               "<!-- REUSE-IgnoreStart -->", ""]
  for pin in pins {
    guard let identity = pin["identity"] as? String, let location = pin["location"] as? String,
          let state = pin["state"] as? [String: String],
          let revision = state["revision"] else { throw ToolError("Invalid dependency pin.") }
    let directory = path("Tuist/.build/checkouts/\(identity)").resolvingSymlinksInPath()
    guard let enumerator = fm.enumerator(at: directory, includingPropertiesForKeys: [.isRegularFileKey])
    else { throw ToolError("Run tuist install first.") }
    var files: [URL] = []
    for case let file as URL in enumerator {
      if file.pathComponents.contains(".git") {
        enumerator.skipDescendants()
        continue
      }
      let name = file.lastPathComponent.uppercased().components(separatedBy: ".")[0]
      if ["LICENSE", "LICENCE", "NOTICE", "COPYING"].contains(name),
         try file.resourceValues(forKeys: [.isRegularFileKey]).isRegularFile == true
      {
        files.append(file)
      }
    }
    try require(!files.isEmpty, "No license found for \(identity)")
    parts += ["## \(identity) \(state["version"] ?? "")", "", "Source: \(location)", "", "Revision: `\(revision)`", ""]
    for file in files.sorted(by: { $0.path < $1.path }) {
      try parts += [
        "### \(file.path.dropFirst(directory.path.count + 1))",
        "",
        "~~~~text",
        read(file).trimmingCharacters(in: .whitespacesAndNewlines),
        "~~~~",
        "",
      ]
    }
    if identity == "swift-toml" {
      let header = try read(directory.appendingPathComponent("Sources/CTomlPlusPlus/toml.hpp"))
      parts += [
        "### Vendored toml++",
        "",
        "~~~~text",
        header.components(separatedBy: "#ifndef")[0].trimmingCharacters(in: .whitespacesAndNewlines),
        "~~~~",
        "",
      ]
    }
  }
  try parts += ["## Catppuccin palette", "", "Source: https://github.com/catppuccin/catppuccin", "", "~~~~text",
                read(path("ThirdParty/Catppuccin.txt")).trimmingCharacters(in: .whitespacesAndNewlines), "~~~~", "",
                "<!-- REUSE-IgnoreEnd -->",
                ""]
  try generated(parts.joined(separator: "\n"), at: path("THIRD_PARTY_NOTICES.md"), check: check)
  print("Validated notices for \(pins.count) resolved packages and Catppuccin.")
}

func releaseNotes() throws -> String {
  let value = try version()
  let lines = try read(path("CHANGELOG.md")).components(separatedBy: "\n")
  guard let start = lines.firstIndex(of: "## \(value)") else { throw ToolError("Missing release changelog.") }
  let body = lines.dropFirst(start + 1).prefix { !$0.hasPrefix("## ") }.joined(separator: "\n")
    .trimmingCharacters(in: .whitespacesAndNewlines)
  try require(!body.isEmpty, "Empty release changelog.")
  return """
  \(body)

  Install (recommended): `mise use -g github:PangMo5/Tatara@\(value)`

  Runtime tools: `mise use -g aqua:cli/cli aqua:Wilfred/difftastic`

  Homebrew: `brew install PangMo5/tap/tatara`

  [Corresponding source](https://github.com/PangMo5/Tatara/releases/download/v\(value)/Tatara-\(
    value
  )-source.tar.gz) · [Licenses and notices](https://github.com/PangMo5/Tatara/blob/v\(value)/THIRD_PARTY_NOTICES.md)
  """ + "\n"
}

func checkTests(_ url: URL) throws {
  let text = try read(url)
  let regex = try NSRegularExpression(pattern: #"Test run with (\d+) tests? (?:in \d+ suites? )?passed"#)
  guard let match = regex.matches(in: text, range: NSRange(text.startIndex..., in: text)).last,
        let range = Range(match.range(at: 1), in: text), let count = Int(text[range]),
        count > 0 else { throw ToolError("No nonzero successful Swift Testing run found.") }
  print("Confirmed \(count) executed Swift Testing tests.")
}

func package(products: URL, architecture: String, output: URL) throws {
  let triple: String
  switch architecture { case "arm64": triple = "aarch64-apple-darwin"
  case "x86_64": triple = "x86_64-apple-darwin"
  default: throw ToolError("Unsupported architecture: \(architecture)") }
  let binary = products.appendingPathComponent("tatara")
  try run("lipo", [binary.path, "-verify_arch", architecture])
  let libraries = try run("otool", ["-arch", architecture, "-L", binary.path], capture: true).components(separatedBy: "\n")
    .dropFirst().map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }
  try require(
    libraries.allSatisfy { $0.hasPrefix("/usr/lib/") || $0.hasPrefix("/System/Library/") },
    "Unexpected non-system dynamic dependency.",
  )
  let stage = try temporary("package")
  defer { try? fm.removeItem(at: stage) }
  try fm.createDirectory(at: stage.appendingPathComponent("bin"), withIntermediateDirectories: true)
  try fm.createDirectory(at: stage.appendingPathComponent("share/tatara"), withIntermediateDirectories: true)
  try fm.createDirectory(at: output, withIntermediateDirectories: true)
  let architectures = try run("lipo", ["-archs", binary.path], capture: true).split(whereSeparator: \.isWhitespace)
  if architectures.count > 1 {
    try run(
      "lipo",
      [binary.path, "-thin", architecture, "-output", stage.appendingPathComponent("bin/tatara").path],
    )
  } else {
    try fm.copyItem(at: binary, to: stage.appendingPathComponent("bin/tatara"))
  }
  for name in ["LICENSE", "THIRD_PARTY_NOTICES.md", "LICENSES"] {
    try fm.copyItem(
      at: path(name),
      to: stage.appendingPathComponent("share/tatara/\(name)"),
    )
  }
  for name in ["README.md", "CONTRIBUTING.md", "LICENSE", "THIRD_PARTY_NOTICES.md", "docs"] {
    try fm.copyItem(
      at: path(name),
      to: stage.appendingPathComponent(name),
    )
  }
  try write("https://github.com/PangMo5/Tatara/tree/v\(version())\n", stage.appendingPathComponent("share/tatara/SOURCE.txt"))
  try run("tar", ["-C", stage.path, "-czf", output.appendingPathComponent("tatara-\(version())-\(triple).tar.gz").path, "."])
}

func installLocal(products: URL, prefix: URL) throws {
  let source = products.appendingPathComponent("tatara")
  try run("codesign", ["--verify", "--strict", source.path])
  try require(
    run(source.path, ["--version"], capture: true).trimmingCharacters(in: .whitespacesAndNewlines) == version(),
    "Built version does not match Project.swift.",
  )
  let bin = prefix.appendingPathComponent("bin")
  let share = prefix.appendingPathComponent("share/tatara")
  try fm.createDirectory(at: bin, withIntermediateDirectories: true)
  try fm.createDirectory(at: share, withIntermediateDirectories: true)
  let staged = bin.appendingPathComponent(".tatara-\(UUID())")
  defer { try? fm.removeItem(at: staged) }
  try fm.copyItem(at: source, to: staged)
  for name in ["LICENSE", "LICENSES", "THIRD_PARTY_NOTICES.md", "README.md", "CONTRIBUTING.md", "docs"] {
    let destination = share.appendingPathComponent(name)
    if fm.fileExists(atPath: destination.path) {
      try fm.removeItem(at: destination)
    }
    try fm.copyItem(at: path(name), to: destination)
  }
  let metadata: [String: Any] = try [
    "source": root.path,
    "source_commit": run("git", ["rev-parse", "HEAD"], capture: true).trimmingCharacters(in: .whitespacesAndNewlines),
    "source_modified": !run("git", ["status", "--porcelain"], capture: true).isEmpty,
    "version": version(), "kind": "local-release-build", "sha256": digest(staged),
    "updated_at": ISO8601DateFormatter().string(from: Date()),
  ]
  try require(
    rename(staged.path, bin.appendingPathComponent("tatara").path) == 0,
    "Atomic executable replacement failed: \(errno)",
  )
  try JSONSerialization.data(withJSONObject: metadata, options: [.prettyPrinted, .sortedKeys])
    .write(to: share.appendingPathComponent("installation.json"), options: .atomic)
  try print("Installed \(version()) at \(bin.path). Restart any running Tatara process.")
}

func formula(artifacts: URL, output: URL) throws {
  let value = try version()
  func sha(_ arch: String) throws
    -> String
  {
    try digest(artifacts.appendingPathComponent("tatara-\(value)-\(arch)-apple-darwin.tar.gz"))
  }
  try write("""
  class Tatara < Formula
    desc "Structural code review workspace for your terminal"
    homepage "https://github.com/PangMo5/Tatara"
    version "\(value)"
    license "AGPL-3.0-only"

  try   on_macos do
      on_arm do
        url "https://github.com/PangMo5/Tatara/releases/download/v\(value)/tatara-\(value)-aarch64-apple-darwin.tar.gz"
        sha256 "\(sha("aarch64"))"
      end
      on_intel do
        url "https://github.com/PangMo5/Tatara/releases/download/v\(value)/tatara-\(value)-x86_64-apple-darwin.tar.gz"
        sha256 "\(sha("x86_64"))"
      end
    end

    depends_on macos: :sequoia
    depends_on "difftastic"
    depends_on "gh"

    def install
      bin.install "bin/tatara"
      (share/"tatara").install Dir["share/tatara/*"]
    end

    test do
      assert_equal version.to_s, shell_output("#{bin}/tatara --version").strip
    end
  end
  """ + "\n", output)
}

func generate(locked: Bool = false) throws {
  try run("tuist", ["install"])
  if locked {
    try run("git", ["diff", "--exit-code", "--", "Tuist/Package.resolved"])
  }
  try run("tuist", ["generate", "--no-open"])
}

