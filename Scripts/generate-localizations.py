#!/usr/bin/env python3
"""Compile the canonical String Catalog into a relocatable CLI's Swift source."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
catalog = json.loads((root / 'SharedResources/Localizable.xcstrings').read_text())
locales = ['en', 'ko', 'ja', 'zh-Hans', 'zh-Hant']
output = ['// Generated by Scripts/generate-localizations.py. Do not edit.',
          '// SPDX-FileCopyrightText: 2026 PangMo5 and contributors',
          '// SPDX-' + 'License-Identifier: AGPL-3.0-only', '',
          'enum LocalizedStrings {', '  static let values: [String: [String: String]] = [']
def literal(text):
    # Swift interpolation cannot be introduced by a catalog value.
    return json.dumps(text, ensure_ascii=False).replace('\\/', '/')
for locale in locales:
    output.append(f'    {literal(locale)}: [')
    for key, entry in sorted(catalog['strings'].items()):
        unit = entry['localizations'][locale]['stringUnit']
        assert unit['state'] == 'translated' and unit['value'].strip(), (locale, key)
        assert '\\(' not in key and '\\(' not in unit['value'], 'Use named format placeholders instead of Swift interpolation'
        output.append(f'      {literal(key)}: {literal(unit["value"])},')
    output.append('    ],')
output.extend(['  ]', '}', ''])
text = '\n'.join(output)
target = root / 'TataraTUI/Sources/Generated/LocalizedStrings.swift'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    assert target.read_text() == text, 'Run python3 Scripts/generate-localizations.py'
else:
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists() or target.read_text() != text:
        target.write_text(text)
print(f'Validated {len(catalog["strings"])} strings across {len(locales)} locales.')
